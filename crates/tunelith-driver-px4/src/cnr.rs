pub fn isdb_t(raw: u16) -> f64 {
    let i = ISDB_T.partition_point(|&v| v <= raw).saturating_sub(1);
    10.0 + 0.5 * i as f64
}

pub fn isdb_s(raw: u16) -> f64 {
    let i = ISDB_S.partition_point(|&v| v >= raw).saturating_sub(1);
    0.1 * i as f64
}

#[cfg(test)]
mod tests {
    #[test]
    fn lookup() {
        assert_eq!(super::isdb_t(0), 10.0);
        assert_eq!(super::isdb_t(0x5a), 10.5);
        assert_eq!(super::isdb_t(0x5b), 10.5);
        assert_eq!(super::isdb_t(0xffff), 34.0);
        assert_eq!(super::isdb_s(0x5af), 0.0);
        assert!((super::isdb_s(0x539) - 0.5).abs() < 1e-9);
        assert!((super::isdb_s(0x14) - 19.1).abs() < 1e-9);
    }
}
