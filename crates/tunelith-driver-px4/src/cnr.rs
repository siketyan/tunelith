/// The C/N in dB of a PT ISDB-T value.
pub fn isdb_t(raw: u32) -> f64 {
    if raw == 0 {
        return 0.0;
    }
    let p = 10.0 * (5_505_024.0 / f64::from(raw)).log10();
    (0.000024 * p.powi(4) - 0.0016 * p.powi(3) + 0.0398 * p.powi(2) + 0.5491 * p + 3.0965).max(0.0)
}

/// The C/N in dB of a PT ISDB-S value.
pub fn isdb_s(raw: u16) -> f64 {
    if raw < 3000 {
        return 0.0;
    }
    let p = f64::from(raw - 3000).sqrt() / 64.0;
    let milli = -1634.6 * p.powi(5) + 14341.0 * p.powi(4) - 50259.0 * p.powi(3)
        + 88977.0 * p.powi(2)
        - 89565.0 * p
        + 58857.0;
    (milli / 1000.0).max(0.0)
}

pub fn cxd_isdb_t(raw: u16) -> f64 {
    let i = CXD_ISDB_T
        .partition_point(|&(v, _)| v <= raw)
        .saturating_sub(1);
    isdb_t(CXD_ISDB_T[i].1)
}

pub fn cxd_isdb_s(raw: u16) -> f64 {
    let i = CXD_ISDB_S
        .partition_point(|&(v, _)| v >= raw)
        .saturating_sub(1);
    isdb_s(CXD_ISDB_S[i].1)
}

#[cfg(test)]
mod tests {
    fn near(a: f64, b: f64) -> bool {
        (a - b).abs() < 0.1
    }

    #[test]
    fn lookup() {
        assert!(near(super::cxd_isdb_t(0), 10.0));
        assert!(near(super::cxd_isdb_t(0x5b), 10.5));
        assert!(near(super::cxd_isdb_t(0xffff), 34.0));
        assert!(near(super::cxd_isdb_s(0x5af), 0.0));
        assert!(near(super::cxd_isdb_s(0x539), 0.5));
        assert!(near(super::cxd_isdb_s(0x14), 20.0));
    }
}
